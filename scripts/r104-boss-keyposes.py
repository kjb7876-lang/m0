#!/usr/bin/env python3
"""R104: turn the Drive boss key-pose sheets (HAPIL accepted batches, catalogued
from LIVE-ASSET-INDEX rev 10) into trimmed runtime frames.

For every set: crop the four 2x2 cells of the original sheet by source_rect,
scale all four by one factor so the recovery pose (pose 4, the neutral stance)
stands TARGET px tall, trim to the union of the four alpha boxes, and save
WebP frames that share one foot pivot (pose-4 alpha bottom, centre x).
Writes r96/runtime-text/assets/r104/bosses/<id>-p{1..4}.webp and
r96/client-source/bosses-r104-data.js.

usage: python3 scripts/r104-boss-keyposes.py /path/to/drive-catalog-dir"""
import json,sys
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'r96/runtime-text/assets/r104/bosses'
TARGET=400;PAD=6;ALPHA=18
def bbox(im):
 a=im.getchannel('A').point(lambda v:255 if v>ALPHA else 0);return a.getbbox()
def main(src):
 src=Path(src);cat=json.loads((src/'catalog.json').read_text())
 OUT.mkdir(parents=True,exist_ok=True);data={}
 for batch,sets in cat['body_batches'].items():
  for s in sets:
   rid=s['runtime_boss_id'];sheet=Image.open(src/s['original_sheet']['path']).convert('RGBA')
   cells=[sheet.crop((x,y,x+w,y+h)) for x,y,w,h in (p['source_rect_xywh'] for p in s['poses'])]
   # common canvas: pad cells to the largest cell so the four share coordinates
   cw=max(c.width for c in cells);ch=max(c.height for c in cells)
   canv=[]
   for c in cells:
    k=Image.new('RGBA',(cw,ch));k.paste(c,((cw-c.width)//2,(ch-c.height)//2));canv.append(k)
   boxes=[bbox(c) for c in canv];b4=boxes[3]
   scale=min(1.0,TARGET/(b4[3]-b4[1]))
   ux0=min(b[0] for b in boxes);uy0=min(b[1] for b in boxes);ux1=max(b[2] for b in boxes);uy1=max(b[3] for b in boxes)
   frames=[]
   for i,c in enumerate(canv):
    crop=c.crop((ux0,uy0,ux1,uy1));w=round(crop.width*scale);h=round(crop.height*scale)
    crop=crop.resize((w,h),Image.LANCZOS);f=Image.new('RGBA',(w+2*PAD,h+2*PAD));f.paste(crop,(PAD,PAD))
    name=f'{rid}-p{i+1}.webp';f.save(OUT/name,'WEBP',quality=84,method=6)
    frames.append({'path':f'assets/r104/bosses/{name}','w':f.width,'h':f.height,'label':s['poses'][i].get('label')})
   px=round(((b4[0]+b4[2])/2-ux0)*scale)+PAD;py=round((b4[3]-uy0)*scale)+PAD;vh=round((b4[3]-b4[1])*scale)
   data[rid]={'set':s['set_id'],'name':s.get('name'),'batch':batch,'pivot':[px,py],'visibleHeight':vh,'frames':frames}
   print(rid,s['set_id'],round(scale,3),[f['w'] for f in frames],vh)
 js='// Generated by scripts/r104-boss-keyposes.py from the Drive HAPIL key-pose batches. Do not edit.\nwindow.__STORYWORLD_BOSS_KEYPOSES_R104_DATA__=Object.freeze('+json.dumps(data,ensure_ascii=False,separators=(',',':'))+');\n'
 (ROOT/'r96/client-source/bosses-r104-data.js').write_text(js)
 print(len(data),'sets')
if __name__=='__main__':main(sys.argv[1] if len(sys.argv)>1 else '/tmp/r104/drive')
