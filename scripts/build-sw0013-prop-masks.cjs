// Bake the R412 wall-placement alpha test for immutable, frequently sampled STORY art.
// By default check the asset manifest and generated table without browser dependencies.
// After building the game and installing Playwright's Chromium and WebKit, use --write
// to regenerate both raster profiles, or --verify-browsers to compare the current pixels.
// Override SW_SITE, CHROMIUM_PATH or WEBKIT_PATH for local installations.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');

const r96 = path.resolve(__dirname, '../r96');
const site = process.env.SW_SITE || path.join(r96, 'hospital-three-pc/site');
const overlay = path.join(r96, 'client-source/props-tidy-r412.js');
const begin = '// BEGIN GENERATED R412 MASKS';
const end = '// END GENERATED R412 MASKS';
const paths = [
  'assets/props/v290/bone_heap.webp', 'assets/props/v290/collapsed_pillar.webp',
  'assets/props/v290/corrupted_shrine.webp', 'assets/props/v290/dead_tree.webp',
  'assets/props/v290/moss_boulders.webp', 'assets/props/v3100/memory_archivist_statue.webp',
  'assets/r105/props/dist02-hands.webp', 'assets/r105/props/dist02-waterweed.webp',
  'assets/r138/props/weed.webp', 'assets/r257/props/weed-opp.webp',
  ...Array.from({length: 12}, (_, i) => 'assets/r99/outdoor/tree-dead-' + String(i).padStart(2, '0') + '.webp'),
  'assets/world-r80/r80-013.webp', 'assets/world-r80/r80-014.webp'
];
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const isTree = name => name.startsWith('assets/r99/outdoor/tree-');
const source = fs.readFileSync(overlay, 'utf8');
const head = source.indexOf(begin);
const tail = source.indexOf(end);
assert.ok(head >= 0 && tail > head && source.lastIndexOf(begin) === head && source.lastIndexOf(end) === tail);

function assetHashes() {
  const {files} = JSON.parse(fs.readFileSync(path.join(r96, 'runtime-manifest.json'), 'utf8'));
  const manifest = new Map(files.map(row => [row.path, row.sha256]));
  return Object.fromEntries(paths.map(name => {
    const sha256 = manifest.get(name);
    assert.match(sha256, /^[0-9a-f]{64}$/, name);
    for (const root of [path.join(r96, 'runtime-text'), site]) {
      const file = path.join(root, name);
      if (fs.existsSync(file)) assert.equal(hash(fs.readFileSync(file)), sha256, 'asset drift: '+file);
    }
    return [name, sha256];
  }));
}
function verifyTable(table) {
  assert.deepEqual(Object.keys(table), paths);
  for (const [name, [width, height, rows]] of Object.entries(table)) {
    assert.ok(width > 0 && height > 0 && width*height < 500000 && rows.length, name);
    const seen = new Set();
    for (const row of rows) {
      const [x,y,w,h,...profiles] = row;
      assert.ok([x,y,w,h].every(Number.isFinite) && x>=0 && y>=0 && w>0 && h>0, name);
      const key = JSON.stringify([x,y,w,h]);
      assert.ok(!seen.has(key), name+' duplicate rectangle'); seen.add(key);
      assert.equal(profiles.length, 2, name);
      for (const profile of profiles) {
        assert.equal(Buffer.from(profile, 'base64').length, 70, name);
        assert.equal(Buffer.from(profile, 'base64').toString('base64'), profile, name);
      }
    }
  }
}
function renderTable(hashes, table) {
  // One line per asset. Hashes remain comments in the shipped client.
  const lines = [begin, '// Generated by scripts/build-sw0013-prop-masks.cjs.', 'const bakedPropMasks={'];
  for (const name of paths) {
    lines.push('// sha256 '+hashes[name]);
    lines.push(JSON.stringify(name)+':'+JSON.stringify(table[name])+(name===paths.at(-1)?'':','));
  }
  lines.push('};', end);
  return lines.join('\n');
}
function readTable(hashes) {
  const block = source.slice(head, tail + end.length);
  const first = block.indexOf('const bakedPropMasks=');
  const last = block.lastIndexOf('};');
  assert.ok(first !== -1 && last>first, 'generated table missing');
  const json = block.slice(first+'const bakedPropMasks='.length, last+1).replace(/^\/\/ sha256 [0-9a-f]{64}$\n/gm,'');
  const table = JSON.parse(json);
  verifyTable(table);
  assert.equal(block, renderTable(hashes, table), 'asset hash or table drift: rebuild masks');
  return table;
}

async function openRasterEngine(engine, name, cropCode) {
  const executablePath = name==='chromium' ? process.env.CHROMIUM_PATH : process.env.WEBKIT_PATH;
  const browser = await engine.launch({executablePath});
  try {
    const page = await browser.newPage();
    const origin = 'http://mask-fixture.test/';
    await page.route(origin+'**', async route => {
      const asset = new URL(route.request().url()).pathname.slice(1);
      if (!asset) return route.fulfill({contentType:'text/html', body:'<!doctype html>'});
      assert.ok(paths.includes(asset), asset);
      await route.fulfill({contentType:'image/webp', body:fs.readFileSync(path.join(site, asset))});
    });
    await page.goto(origin);
    await page.addScriptTag({content:cropCode});
    const inputs = await page.evaluate(async names => {
      window.propInputs = {};
      const result = {};
      for (const name of names) {
        const image = new Image(); image.src = name; await image.decode();
        window.propInputs[name] = image;
        const crop = window.imageCrop(image);
        if (!crop) throw Error('blank or unavailable source: '+name);
        result[name] = [image.naturalWidth, image.naturalHeight, [crop.x,crop.y,crop.w,crop.h]];
      }
      return result;
    }, paths);
    return {browser,page,inputs};
  } catch (error) { await browser.close(); throw error; }
}
function rectsFor(engines, name) {
  const [width,height] = engines[0].inputs[name];
  const found = new Map();
  const add = rect => found.set(JSON.stringify(rect), rect);
  add([0,0,width,height]);
  for (const engine of engines) {
    assert.deepEqual(engine.inputs[name].slice(0,2), [width,height], name);
    // The sway animation samples each frame using the current frame's trim.
    for (const input of isTree(name)?paths.filter(isTree):[name]) {
      const [x,y,w,h]=engine.inputs[input][2];
      add([x,y,w,h]);
      // Native drawing can clip the extra alpha-border pixel at the bottom or right edge.
      add([x,y,Math.min(w,width-x),Math.min(h,height-y)]);
    }
  }
  return [...found.values()].sort((a,b) => {
    for (let i=0;i<4;i++) if (a[i]!==b[i]) return a[i]-b[i];
    return 0;
  });
}
async function measureMasks(page, crops) {
  return page.evaluate(crops => {
    const canvas = document.createElement('canvas');
    canvas.width=20; canvas.height=28;
    const ctx=canvas.getContext('2d',{willReadFrequently:true});
    const result={};
    for (const [name, rects] of Object.entries(crops)) {
      result[name]=rects.map(rect => {
        ctx.clearRect(0,0,20,28);
        ctx.drawImage(window.propInputs[name],...rect,0,0,20,28);
        const data=ctx.getImageData(0,0,20,28).data;
        const bytes=new Uint8Array(70);
        for (let i=0;i<560;i++) if (data[4*i+3]>=80) bytes[i>>3]|=1<<(i%8);
        return btoa(String.fromCharCode(...bytes));
      });
    }
    return result;
  }, crops);
}

async function main() {
  const mode=process.argv[2] || '--check';
  assert.ok(['--check','--write','--verify-browsers'].includes(mode), 'use --check, --write or --verify-browsers');
  const hashes=assetHashes();
  if (mode==='--check') {
    const table=readTable(hashes);
    console.log('R412 asset hashes and table structure verified:',paths.length,'sources,',
      Object.values(table).reduce((n,row)=>n+row[2].length,0),'rectangles');
    return;
  }
  const html=fs.readFileSync(path.join(r96,'runtime-text/index.html'),'utf8');
  const cropCode=html.match(/^function imageCrop\(im\)\{[^\n]+$/m)?.[0];
  assert.ok(cropCode,'could not locate the real imageCrop()');
  const playwright=require('playwright');
  const engines=[];
  try {
    for (const name of ['chromium','webkit']) engines.push(await openRasterEngine(playwright[name],name,cropCode));
    const crops=Object.fromEntries(paths.map(name=>[name,rectsFor(engines,name)]));
    const results=[];
    for (const engine of engines) results.push(await measureMasks(engine.page,crops));
    const table=Object.fromEntries(paths.map(name=>[
      name,[...engines[0].inputs[name].slice(0,2),crops[name].map((rect,i)=>[...rect,results[0][name][i],results[1][name][i]])]
    ]));
    verifyTable(table);
    if (mode==='--write') {
      // Another feature may have edited the overlay while browsers were rendering.
      const current=fs.readFileSync(overlay,'utf8');
      fs.writeFileSync(overlay,current.slice(0,current.indexOf(begin))+renderTable(hashes,table)+current.slice(current.indexOf(end)+end.length));
    } else {
      assert.deepEqual(table,readTable(hashes),'native mask differs: review raster profiles before regenerating');
      const verifyNative=require('../r96/qa/sw0013/prop-mask-native.cjs');
      for (const [index,name] of ['chromium','webkit'].entries())
        await verifyNative(engines[index].page,source,table,name);
    }
    console.log('R412 native browser masks',mode,paths.length,'sources,',Object.values(crops).reduce((n,v)=>n+v.length,0),'rectangles');
  } finally { for (const engine of engines) await engine.browser.close(); }
}
main().catch(err=>{console.error(err);process.exitCode=1;});
