#!/usr/bin/env python3
"""R463: data for sin-boss-art-r463.js (7대죄 보스 그림 한 형태·한 크기).

Reads the source actor rows of the seven-sins bosses from r96/runtime-text/index.html
(actionSpritesByPhase / actionSprites / phaseSprites), and writes
r96/client-source/sin-boss-art-r463-data.js:
  zone      boss room id
  idle/attack  the phase-0 (story) body paths the boss keeps for the whole fight
  remap     every other-phase or generic body path -> 'idle' | 'attack'
  vis       visible body height (source px) of each drawn art family, measured on the
            family's standing frame: actors-normalized phase-0 idle alpha box,
            R104 key poses (scaled so pose 4 = 400 px), R380 sheet visibleHeight.
Mammon (b06/b06b) is left out on purpose (Codex owns it).
usage: python3 scripts/r463-sin-boss-art.py"""
import json,re
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
HTML=ROOT/'r96/runtime-text/index.html'
ASSETS=ROOT/'r96/runtime-text'
OUT=ROOT/'r96/client-source/sin-boss-art-r463-data.js'
BOSSES={'b02-boss':'ep1b02','b03-boss':'ep1b03','b04-boss':'ep1b04','b05-boss':'ep1b05','b07-boss':'ep1b07','b08-boss':'ep1b08'}
IDLE={'idle','move','hit','stagger','death'}
def norm(p):return re.sub(r'^\./','',p)
def alpha_h(path):
  im=Image.open(path).convert('RGBA');bb=im.getchannel('A').point(lambda v:255 if v>40 else 0).getbbox();return bb[3]-bb[1]
def find_asset(rel):
  for base in (ASSETS,ROOT/'r96/hospital-three-pc/site'):
    if (base/rel).exists():return base/rel
  raise SystemExit('missing asset '+rel)
s=HTML.read_text(encoding='utf8');dec=json.JSONDecoder()
r104=json.loads(re.search(r'Object\.freeze\((\{.*\})\)',(ROOT/'r96/client-source/bosses-r104-data.js').read_text(encoding='utf8')).group(1))
r380=json.loads(find_asset('assets/r380/mobs/index.json').read_text(encoding='utf8'))
out={}
for bid,zone in BOSSES.items():
  row=None
  for m in re.finditer(r'\{"id":"%s","name"'%re.escape(bid),s):
    try:o,_=dec.raw_decode(s[m.start():])
    except ValueError:continue
    if 'actionSpritesByPhase' in o:row=o
  if not row:raise SystemExit('no source actor for '+bid)
  ph=row['actionSpritesByPhase'];p0=ph[0]
  idle,attack=norm(p0['idle']),norm(p0['attackA'])
  own={norm(v) for v in p0.values()}
  remap={}
  for k,v in list((row.get('actionSprites') or {}).items())+[(k,v) for a in ph[1:] for k,v in a.items()]:
    v=norm(v)
    if v not in own:remap[v]='idle' if k in IDLE else 'attack'
  for v in (row.get('phaseSprites') or [])[1:]:
    v=norm(v)
    if v not in own:remap.setdefault(v,'idle')
  vis={}
  h=alpha_h(find_asset(idle))
  for v in list(own)+list(remap):vis[v]=h
  if bid in r104:
    for f in r104[bid]['frames']:vis[f['path']]=r104[bid]['visibleHeight']
  for mob in r380['mobs']:
    if mob['actor'].get('zone')==zone and mob['actor'].get('boss'):vis[mob['path']]=mob['visibleHeight']
  out[bid]={'zone':zone,'name':row['name'],'idle':idle,'attack':attack,'remap':dict(sorted(remap.items())),'vis':dict(sorted(vis.items()))}
OUT.write_text('// Generated by scripts/r463-sin-boss-art.py from the source actor rows (index.html), R104 key poses and the R380 sheet index. Do not edit.\n'
 'window.__STORYWORLD_SIN_BOSS_ART_R463_DATA__=Object.freeze('+json.dumps(out,ensure_ascii=False,separators=(',',':'))+');\n',encoding='utf8')
for b,v in out.items():print(b,v['zone'],len(v['remap']),'remapped',{k:round(x) for k,x in v['vis'].items() if 'r104' in k or 'r380' in k} or '', 'normH',v['vis'][v['idle']])
